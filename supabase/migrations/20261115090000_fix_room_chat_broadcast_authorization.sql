begin;

-- Realtime evaluates channel policies as the signed-in client. Keep the
-- membership lookup inside a narrowly-scoped SECURITY DEFINER helper instead
-- of requiring clients to execute can_use_room_chat(room, mode, arbitrary_uid).
create or replace function public.can_receive_room_chat_broadcast(p_topic text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  v_room_mode text := split_part(p_topic, ':', 2);
  v_room_key text := split_part(p_topic, ':', 3);
begin
  if uid is null then return false; end if;

  -- The legacy, always-on rooms keep their existing topic names.
  if p_topic = 'room:official-live' then
    return public.can_use_room_chat('official-live', 'official', uid)
      and exists (
        select 1 from public.room_sessions s
        where s.room_id = 'official-live' and s.room_mode = 'official'
          and s.user_id = uid and s.left_at is null
      )
      and not exists (
        select 1 from public.room_blocks b
        where b.room_id = 'official-live' and b.user_id = uid and b.ends_at > now()
      );
  end if;

  if p_topic = 'room:general' then
    return not public.is_faculty_account(uid)
      and exists (
        select 1 from public.profiles p
        where p.id = uid and p.role in ('student', 'super_admin')
      );
  end if;

  -- New private channels are scoped as room:<mode>:<room-id> and only active
  -- members may receive them. Unofficial identities remain in the anonymous
  -- message payload generated by the trigger.
  if split_part(p_topic, ':', 1) <> 'room'
    or v_room_mode not in ('official', 'unofficial')
    or v_room_key = '' then
    return false;
  end if;

  return public.can_use_room_chat(v_room_key, v_room_mode, uid)
    and exists (
      select 1 from public.room_sessions s
      where s.room_id = v_room_key and s.room_mode = v_room_mode
        and s.user_id = uid and s.left_at is null
    )
    and not exists (
      select 1 from public.room_blocks b
      where b.room_id = v_room_key and b.user_id = uid and b.ends_at > now()
    );
end;
$$;

revoke all on function public.can_receive_room_chat_broadcast(text)
  from public, anon, authenticated;
grant execute on function public.can_receive_room_chat_broadcast(text)
  to authenticated;

drop policy if exists "Authenticated users can receive room broadcasts"
  on realtime.messages;
create policy "Authenticated users can receive room broadcasts"
  on realtime.messages for select to authenticated
  using (
    extension = 'broadcast'
    and public.can_receive_room_chat_broadcast(realtime.topic())
  );

notify pgrst, 'reload schema';
commit;
